
#!/usr/bin/env python3
"""
Create a combined presence/absence matrix from HMMER summary results.

Criteria:
    - E-value < 1e-5
    - HMM coverage > 40%

Output:
    One TSV file with HMM profiles as rows and samples as columns.
    1 = at least one qualifying hit
    0 = no qualifying hit
"""

import argparse
from pathlib import Path

import pandas as pd


def parse_args():
    parser = argparse.ArgumentParser(
        description=(
            "Create one combined HMM presence/absence matrix "
            "from HMMER summary results."
        )
    )

    parser.add_argument(
        "--input",
        required=True,
        type=Path,
        help="Path to hits.tsv generated by the HMMER summarizer.",
    )

    parser.add_argument(
        "--hmm-dir",
        required=True,
        type=Path,
        help="Directory containing the .hmm profiles.",
    )

    parser.add_argument(
        "--samples",
        nargs="*",
        default=None,
        help=(
            "Optional complete list of sample names. "
            "Use this to include samples with no qualifying hits."
        ),
    )

    parser.add_argument(
        "--output",
        required=True,
        type=Path,
        help="Output directory for the combined matrix.",
    )

    parser.add_argument(
        "--evalue",
        type=float,
        default=1e-5,
        help="Maximum E-value, exclusive (default: 1e-5).",
    )

    parser.add_argument(
        "--coverage",
        type=float,
        default=40.0,
        help="Minimum HMM coverage percentage, exclusive (default: 40).",
    )

    return parser.parse_args()


def main():
    args = parse_args()

    # Validate input paths
    if not args.input.is_file():
        raise SystemExit(f"Input file not found: {args.input}")

    if not args.hmm_dir.is_dir():
        raise SystemExit(f"HMM directory not found: {args.hmm_dir}")

    # Find all HMM profiles, including subdirectories
    hmm_files = sorted(args.hmm_dir.rglob("*.hmm"))

    if not hmm_files:
        raise SystemExit(f"No .hmm files found in {args.hmm_dir}")

    # Use HMM filenames as identifiers
    hmm_ids = sorted(
        path.name.removesuffix(".hmm")
        for path in hmm_files
    )

    if len(hmm_ids) != len(set(hmm_ids)):
        raise SystemExit(
            "Duplicate HMM filenames found in different directories. "
            "Please use unique filenames or adjust the HMM identifiers."
        )

    # Load the HMMER summary
    hits = pd.read_csv(args.input, sep="\t")

    required_columns = {
        "sample",
        "hmm_id",
        "evalue",
        "hmm_coverage_pct",
    }

    missing_columns = required_columns - set(hits.columns)

    if missing_columns:
        raise SystemExit(
            "Missing required columns in hits.tsv: "
            + ", ".join(sorted(missing_columns))
        )

    # Determine sample names
    if args.samples:
        samples = list(dict.fromkeys(args.samples))
    else:
        samples = sorted(
            hits["sample"].dropna().astype(str).unique()
        )

    if not samples:
        raise SystemExit(
            "No samples found. Provide the complete sample list "
            "using --samples."
        )

    # Convert columns to numeric values
    hits["evalue"] = pd.to_numeric(
        hits["evalue"], errors="coerce"
    )

    hits["hmm_coverage_pct"] = pd.to_numeric(
        hits["hmm_coverage_pct"], errors="coerce"
    )

    hits["sample"] = hits["sample"].astype("string")
    hits["hmm_id"] = hits["hmm_id"].astype("string")

    # Apply both strict thresholds
    passing = hits[
        (hits["evalue"] < args.evalue)
        & (hits["hmm_coverage_pct"] > args.coverage)
    ].copy()

    # Initialize every profile/sample combination as absent
    matrix = pd.DataFrame(
        0,
        index=hmm_ids,
        columns=samples,
        dtype=int,
    )

    recognized_hmms = set(hmm_ids)
    recognized_samples = set(samples)

    # Report identifiers that do not match
    passing_hmms = set(passing["hmm_id"].dropna())
    unknown_hmms = passing_hmms - recognized_hmms

    if unknown_hmms:
        print(
            "Warning: HMM identifiers in hits.tsv do not match "
            "the profile filenames:"
        )
        for hmm_id in sorted(unknown_hmms):
            print(f"  {hmm_id}")

    passing_samples = set(passing["sample"].dropna())
    unknown_samples = passing_samples - recognized_samples

    if unknown_samples:
        print("Warning: hits found for samples outside the sample list:")
        for sample in sorted(unknown_samples):
            print(f"  {sample}")

    # Mark presence if at least one hit passes both thresholds
    for _, hit in passing.iterrows():
        hmm_id = hit["hmm_id"]
        sample = hit["sample"]

        if (
            pd.notna(hmm_id)
            and pd.notna(sample)
            and hmm_id in recognized_hmms
            and sample in recognized_samples
        ):
            matrix.loc[hmm_id, sample] = 1

    # Save one combined table
    args.output.mkdir(parents=True, exist_ok=True)

    output_file = args.output / "presence_absence_all_samples.tsv"

    matrix.index.name = "hmm_id"
    matrix.to_csv(output_file, sep="\t")

    print("\nPresence/absence matrix completed.")
    print(f"HMM profiles: {len(hmm_ids)}")
    print(f"Samples: {len(samples)}")
    print(f"E-value threshold: < {args.evalue}")
    print(f"HMM coverage threshold: > {args.coverage}%")
    print(f"Qualifying protein hits: {len(passing)}")
    print(
        "Profiles present in at least one sample: "
        f"{(matrix.sum(axis=1) > 0).sum()}"
    )
    print(f"Output file: {output_file.resolve()}")


if __name__ == "__main__":
    main()

